logger = logging.getLogger(__name__)


class SearchOrchestrator:
    """
    Orchestrates search operations based on LLM-generated plans.
    
    The orchestrator:
    1. Receives structured plans from LLM
    2. Executes each action in the plan
    3. Coordinates multiple search services
    4. Merges results intelligently
    5. Never exposes database layer to LLM
    """
    
    def __init__(self, use_mock_llm: bool = True):
        """Initialize search orchestrator with all required services"""
        self.llm_intelligence = LLMIntelligence(use_mock_llm=use_mock_llm)
        self.search_service = SearchService()
        self.timeline_builder = TimelineBuilder()
        self.clip_service = ClipService()
        self.investigation_service = InvestigationService()
        
        logger.info("🎼 Search Orchestrator initialized")
    
    def execute_natural_language_query(
        self, 
        user_query: str, 
        db: Session,
        context: Optional[Dict] = None,
        max_results: int = 50
    ) -> Dict[str, Any]:
        """
        Execute natural language query end-to-end
        
        Args:
            user_query: Natural language query from user
            db: Database session
            context: Optional context (video_id, camera_id, etc.)
            max_results: Maximum results to return
            
        Returns:
            Comprehensive search results
        """
        logger.info(f"🎼 Executing natural language query: '{user_query}'")
        
        try:
            # Step 1: Parse query with LLM
            search_plan = self.llm_intelligence.parse_query(user_query, context)
            
            # Step 2: Execute the plan
            results = self.execute_search_plan(search_plan, db, context, max_results)
            
            # Step 3: Add LLM explanation to results
            results['llm_analysis'] = {
                'original_query': user_query,
                'plan_explanation': self.llm_intelligence.explain_plan(search_plan),
                'confidence': search_plan.confidence,
                'query_type': search_plan.query_type
            }
            
            logger.info(f"✅ Natural language query completed: {len(results.get('results', []))} results")
            return results
            
        except Exception as e:
            logger.error(f"❌ Natural language query failed: {e}")
            return {
                'status': 'error',
                'error': f'Query execution failed: {str(e)}',
                'original_query': user_query,
                'timestamp': datetime.now().isoformat()
            }
    
    def execute_search_plan(
        self,
        plan: SearchPlan,
        db: Session,
        context: Optional[Dict] = None,
        max_results: int = 50
    ) -> Dict[str, Any]:
        """
        Execute a structured search plan
        
        Args:
            plan: SearchPlan generated by LLM
            db: Database session
            context: Optional context
            max_results: Maximum results to return
            
        Returns:
            Orchestrated search results
        """
        logger.info(f"🎼 Executing search plan: {plan.query_type}")
        
        # Initialize result container
        orchestrated_results = {
            'plan_type': plan.query_type,
            'primary_object': plan.primary_object,
            'attributes': plan.attributes,
            'actions_executed': [],
            'results': [],
            'timeline': [],
            'clips': [],
            'statistics': {},
            'related_tracks': [],
            'status': 'success',
            'timestamp': datetime.now().isoformat()
        }
        
        try:
            # Execute each action in the plan
            for action in plan.actions:
                logger.info(f"🔧 Executing action: {action.value}")
                
                if action == ActionType.SEARCH_TEXT:
                    text_results = self._execute_text_search(plan, db, context, max_results)
                    orchestrated_results['results'].extend(text_results)
                    
                elif action == ActionType.SEARCH_EMBEDDINGS:
                    embedding_results = self._execute_embedding_search(plan, db, context, max_results)
                    orchestrated_results['results'].extend(embedding_results)
                    
                elif action == ActionType.SEARCH_EVENTS:
                    event_results = self._execute_event_search(plan, db, context, max_results)
                    orchestrated_results['results'].extend(event_results)
                    
                elif action == ActionType.SEARCH_TIME_RANGE:
                    time_results = self._execute_time_search(plan, db, context, max_results)
                    orchestrated_results['results'].extend(time_results)
                    
                elif action == ActionType.BUILD_TIMELINE:
                    timeline = self._build_timeline(orchestrated_results['results'], db)
                    orchestrated_results['timeline'] = timeline
                    
                elif action == ActionType.RETRIEVE_CLIPS:
                    clips = self._retrieve_clips(orchestrated_results['results'][:10], db)
                    orchestrated_results['clips'] = clips
                    
                elif action == ActionType.ANALYZE_MOVEMENT:
                    movement_analysis = self._analyze_movement(orchestrated_results['results'], db)
                    orchestrated_results['movement_analysis'] = movement_analysis
                    
                elif action == ActionType.FIND_SIMILAR:
                    similar_tracks = self._find_similar_tracks(orchestrated_results['results'], db)
                    orchestrated_results['related_tracks'] = similar_tracks
                    
                elif action == ActionType.COUNT_OBJECTS:
                    statistics = self._count_objects(plan, db, context)
                    orchestrated_results['statistics'] = statistics
                    
                elif action == ActionType.TRACK_DURATION:
                    duration_results = self._filter_by_duration(plan, db, context, max_results)
                    orchestrated_results['results'].extend(duration_results)
                
                orchestrated_results['actions_executed'].append(action.value)
            
            # Remove duplicates and sort results
            orchestrated_results['results'] = self._deduplicate_and_rank_results(
                orchestrated_results['results']
            )
            
            # Generate summary statistics
            orchestrated_results['summary'] = self._generate_summary(orchestrated_results)
            
            logger.info(f"✅ Search plan executed: {len(orchestrated_results['results'])} results")
            return orchestrated_results
            
        except Exception as e:
            logger.error(f"❌ Search plan execution failed: {e}")
            orchestrated_results['status'] = 'error'
            orchestrated_results['error'] = str(e)
            return orchestrated_results
    
    def _execute_text_search(
        self, 
        plan: SearchPlan, 
        db: Session, 
        context: Optional[Dict], 
        max_results: int
    ) -> List[Dict[str, Any]]:
        """Execute text-based search"""
        
        # Build search query from plan attributes
        search_terms = []
        
        if 'headwear' in plan.attributes:
            search_terms.append(plan.attributes['headwear'])
        if 'clothing' in plan.attributes:
            search_terms.append(plan.attributes['clothing'])
        if 'accessory' in plan.attributes:
            search_terms.append(plan.attributes['accessory'])
        if 'color' in plan.attributes:
            search_terms.append(plan.attributes['color'])
        if 'search_term' in plan.attributes:
            search_terms.append(plan.attributes['search_term'])
        
        search_query = ' '.join(search_terms) if search_terms else 'person'
        
        # Execute text search
        try:
            results = self.search_service.text_search(search_query, db, max_results)
            return [self._format_search_result(r, 'text_search') for r in results]
        except Exception as e:
            logger.error(f"Text search failed: {e}")
            return []
    
