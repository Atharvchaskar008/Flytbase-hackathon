    def _execute_event_search(
        self, 
        plan: SearchPlan, 
        db: Session, 
        context: Optional[Dict], 
        max_results: int
    ) -> List[Dict[str, Any]]:
        """Execute event-based search"""
        
        # Build event query based on plan
        event_filters = {}
        
        if 'movement_type' in plan.attributes:
            movement_type = plan.attributes['movement_type']
            if movement_type == 'entrance':
                event_filters['event_type'] = 'track_started'
            elif movement_type == 'exit':
                event_filters['event_type'] = 'track_ended'
            else:
                event_filters['event_type'] = 'track_updated'
        
        # Query events
        query = db.query(Event)
        
        if 'event_type' in event_filters:
            query = query.filter(Event.event_type == event_filters['event_type'])
        
        if context and 'video_id' in context:
            query = query.filter(Event.video_id == context['video_id'])
        
        events = query.order_by(Event.timestamp.desc()).limit(max_results).all()
        
        return [
            {
                'result_type': 'event_match',
                'event_id': str(event.id),
                'track_id': str(event.track_id) if event.track_id else None,
                'event_type': event.event_type,
                'timestamp': event.timestamp.isoformat(),
                'confidence': event.score or 0.8,
                'source': 'event_search'
            }
            for event in events
        ]
    
    def _execute_time_search(
        self, 
        plan: SearchPlan, 
        db: Session, 
        context: Optional[Dict], 
        max_results: int
    ) -> List[Dict[str, Any]]:
        """Execute time-based search"""
        
        # Parse temporal constraints
        start_time = None
        end_time = None
        
        if 'start_time' in plan.temporal_constraints:
            # Parse time like "17:00" to today at that time
            time_str = plan.temporal_constraints['start_time']
            today = datetime.now().date()
            start_time = datetime.combine(today, datetime.strptime(time_str, '%H:%M').time())
        
        if 'end_time' in plan.temporal_constraints:
            time_str = plan.temporal_constraints['end_time']
            today = datetime.now().date()
            end_time = datetime.combine(today, datetime.strptime(time_str, '%H:%M').time())
        
        # Query events in time range
        query = db.query(Event)
        
        if start_time:
            query = query.filter(Event.timestamp >= start_time)
        if end_time:
            query = query.filter(Event.timestamp <= end_time)
        
        if context and 'video_id' in context:
            query = query.filter(Event.video_id == context['video_id'])
        
        events = query.order_by(Event.timestamp.asc()).limit(max_results).all()
        
        return [
            {
                'result_type': 'time_match',
                'event_id': str(event.id),
                'track_id': str(event.track_id) if event.track_id else None,
                'timestamp': event.timestamp.isoformat(),
                'event_type': event.event_type,
                'source': 'time_search'
            }
            for event in events
        ]
    
    def _filter_by_duration(
        self, 
        plan: SearchPlan, 
        db: Session, 
        context: Optional[Dict], 
        max_results: int
    ) -> List[Dict[str, Any]]:
        """Filter tracks by duration"""
        
        min_duration = plan.attributes.get('min_duration_seconds', 60)
        
        # Get tracks and calculate durations
        query = db.query(Track)
        
        if context and 'video_id' in context:
            query = query.filter(Track.video_id == context['video_id'])
        
        tracks = query.all()
        
        duration_results = []
        for track in tracks:
            if track.last_seen and track.first_seen:
                duration = (track.last_seen - track.first_seen).total_seconds()
                if duration >= min_duration:
                    duration_results.append({
                        'result_type': 'duration_match',
                        'track_id': str(track.id),
                        'duration_seconds': duration,
                        'first_seen': track.first_seen.isoformat(),
                        'last_seen': track.last_seen.isoformat(),
                        'source': 'duration_filter'
                    })
        
        # Sort by duration (longest first)
        duration_results.sort(key=lambda x: x['duration_seconds'], reverse=True)
        
        return duration_results[:max_results]
    
    def _count_objects(
        self, 
        plan: SearchPlan, 
        db: Session, 
        context: Optional[Dict]
    ) -> Dict[str, Any]:
        """Count objects based on plan"""
        
        count_object = plan.attributes.get('count_object', 'person')
        
        statistics = {}
        
        if count_object == 'person' or count_object == 'tracks':
            query = db.query(Track)
            if context and 'video_id' in context:
                query = query.filter(Track.video_id == context['video_id'])
            statistics['total_tracks'] = query.count()
            
        if count_object == 'events':
            query = db.query(Event)
            if context and 'video_id' in context:
                query = query.filter(Event.video_id == context['video_id'])
            statistics['total_events'] = query.count()
            
            # Count by event type
            event_types = db.query(Event.event_type, db.func.count(Event.id)).group_by(Event.event_type).all()
            statistics['events_by_type'] = {event_type: count for event_type, count in event_types}
        
        return statistics
    
    def _build_timeline(self, results: List[Dict], db: Session) -> List[Dict[str, Any]]:
        """Build timeline from search results"""
        # Extract unique event IDs from results
        event_ids = [result['event_id'] for result in results if 'event_id' in result]
        if event_ids:
            events = db.query(Event).filter(Event.id.in_(event_ids)).order_by(Event.timestamp.asc()).all()
            return self.timeline_builder.build_events_timeline(events)

        description_ids = [result['description_id'] for result in results if 'description_id' in result]
        if description_ids:
            descriptions = db.query(Description).filter(Description.id.in_(description_ids)).order_by(Description.timestamp.asc()).all()
            timeline = []
            for desc in descriptions:
                timeline.append({
                    'time': desc.timestamp.strftime('%H:%M:%S') if desc.timestamp else None,
                    'timestamp': desc.timestamp.isoformat() if desc.timestamp else None,
                    'event_type': 'description_match',
                    'track_id': str(desc.track_id) if desc.track_id else None,
                    'description': desc.description,
                    'confidence': desc.confidence,
                    'metadata': desc.desc_metadata or {},
                })
            return timeline

        return []
    
    def _retrieve_clips(self, results: List[Dict], db: Session) -> List[Dict[str, Any]]:
        """Retrieve clips for search results"""
        clips = []
        for result in results[:5]:  # Limit to top 5 results
            if 'event_id' in result:
                try:
                    clip_info = self.clip_service.extract_clip(result['event_id'], db)
                    clips.append(clip_info)
                except Exception as e:
                    logger.warning(f"Failed to extract clip for event {result['event_id']}: {e}")
        return clips
    
    def _format_search_result(self, result: Any, result_type: str) -> Dict[str, Any]:
        """Format search result for consistent output"""
        return {
            'result_type': result_type,
            'data': result,
            'timestamp': datetime.now().isoformat(),
            'source': result_type
        }
    
    def _deduplicate_and_rank_results(self, results: List[Dict]) -> List[Dict]:
        """Remove duplicates and rank results by relevance"""
        # Simple deduplication by track_id
        seen_tracks = set()
        deduplicated = []
        
        for result in results:
            track_id = result.get('track_id')
            if track_id and track_id in seen_tracks:
                continue
            if track_id:
                seen_tracks.add(track_id)
            deduplicated.append(result)
        
        # Sort by confidence/similarity if available
        def get_confidence(result):
            return result.get('similarity', result.get('confidence', 0.5))
        
        deduplicated.sort(key=get_confidence, reverse=True)
        
        return deduplicated
    
    def _generate_summary(self, orchestrated_results: Dict) -> Dict[str, Any]:
        """Generate summary of orchestrated results"""
        return {
            'total_results': len(orchestrated_results['results']),
            'unique_tracks': len(set(r.get('track_id') for r in orchestrated_results['results'] if r.get('track_id'))),
            'timeline_entries': len(orchestrated_results['timeline']),
            'clips_available': len(orchestrated_results['clips']),
            'actions_executed': len(orchestrated_results['actions_executed']),
            'execution_time': datetime.now().isoformat()
        }
    
